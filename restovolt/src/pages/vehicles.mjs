function combos(v) {
  return PRESETS.map((p) => {
    const sel = recommend(v, p.goals, COMPONENTS);
    if (!sel) return null;
    const est = estimate(v, sel, COMPONENTS, p.goals);
    const qs = new URLSearchParams({ v: v.id, ...sel }).toString();
    return { ...p, sel, est, href: `/configurator?${qs}` };
  }).filter(Boolean);
}

